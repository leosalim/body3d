"""Writes src/catalog.generated.js from anatomy.py (the single source of names and groups).

    python catalog_js.py

build.py runs it too, so the catalog always matches the table the models were built from.
"""
from __future__ import annotations

import json
import pathlib

import anatomy

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "catalog.generated.js"


def _label(en: str, pt: str) -> dict:
    return {"en": en, "pt-BR": pt}


def _array(name: str, doc: str, rows: list[dict]) -> list[str]:
    """One entry per line: small diffs and a readable file."""
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False, separators=(", ", ": ")) for r in rows)
    return [f"/** {doc} */", f"export const {name} = [\n{body}\n]", ""]


def main() -> None:
    areas = [{"id": a, "label": _label(en, pt)} for a, en, pt in anatomy.AREAS]
    groups = [{"id": g, "area": area, "label": _label(en, pt)} for g, en, pt, area in anatomy.GROUPS]
    muscles = [{"id": mid, "group": group, "label": _label(en, pt)} for mid, _s, en, pt, group in anatomy.MUSCLES]
    muscles += [{"id": mid, "group": group, "label": _label(en, pt)} for mid, en, pt, group in anatomy.SYNTHETIC]
    muscles.sort(key=lambda m: m["id"])
    tissues = [{"id": tid, "label": _label(en, pt)} for tid, _s, en, pt, _sided in anatomy.TISSUES]
    tissues += [{"id": tid, "label": _label(en, pt)} for tid, en, pt in anatomy.SYNTHETIC_TISSUES]
    regions = [{"id": rid, "sided": sided, "groups": groups_, "label": _label(en, pt)}
               for rid, en, pt, sided, groups_ in anatomy.REGIONS]
    training = [{"id": tid, "label": _label(en, pt), "targets": targets} for tid, en, pt, targets in anatomy.TRAINING_GROUPS]
    js = [
        "// Generated by pipeline/catalog_js.py from pipeline/anatomy.py — do not edit by hand.",
        "// Labels: English (`en`) and Brazilian Portuguese (`pt-BR`).",
        "",
        *_array("AREAS", "Body areas, to arrange the activatable groups in a user interface.", areas),
        *_array("GROUPS", "Activatable anatomical groups: id, body area, label.", groups),
        *_array("MUSCLES", "Muscles (without side): id, group, label. Parts in the GLB use `<id>_l` / `<id>_r`.", muscles),
        *_array("TISSUES", "Connective tissue drawn on the model (never activated).", tissues),
        *_array("REGIONS", "Fit regions: one morph target each (per side for the limbs), weights scale their groups.", regions),
        *_array("TRAINING_GROUPS", "Training groups (gym vocabulary) → anatomical groups or muscles, with weights.", training),
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(js), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(HERE.parent)}: {len(groups)} groups, {len(muscles)} muscles, "
          f"{len(training)} training groups")


if __name__ == "__main__":
    anatomy.check()
    main()
