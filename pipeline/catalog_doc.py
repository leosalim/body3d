"""Writes docs/catalog.md: what BodyParts3D has and what the model uses.

    python catalog_doc.py        (after catalog.py)
"""
from __future__ import annotations

import collections
import json
import pathlib

import anatomy
import bp3d

HERE = pathlib.Path(__file__).resolve().parent
DOCS = HERE.parent / "docs"

SYSTEM_NAMES = {"muscle": "muscle", "bone": "bone", "cartilage": "cartilage", "tendon": "tendon",
                "ligament": "ligament / fascia", "artery": "artery", "vein": "vein", "nerve": "nervous system",
                "skin": "skin", "other": "viscera and other"}


def _rows_for(src: str, rows: list[dict], by_name: dict) -> list[dict]:
    if src.startswith("="):
        return [next(x for x in rows if x["file"] == src[1:])]
    return by_name[src]


def main() -> None:
    with open(HERE.parent / "catalog" / "bp3d-elements.json", encoding="utf-8") as fh:
        rows = json.load(fh)
    by_name = collections.defaultdict(list)
    for r in rows:
        by_name[r["name"]].append(r)
    systems = collections.Counter(r["system"] for r in rows)
    faces = collections.Counter()
    for r in rows:
        faces[r["system"]] += r["faces"]
    group_label = {g: en for g, en, _pt, _area in anatomy.GROUPS}

    out = []
    w = out.append
    w("# Catalog — BodyParts3D in the model")
    w("")
    w("Generated by `pipeline/catalog_doc.py` from `pipeline/anatomy.py` and `catalog/bp3d-elements.json`. "
      "Do not edit by hand.")
    w("")
    w(f"Source: BodyParts3D 4.0 (DBCLS, 2013; licence updated in 2025). {bp3d.ATTRIBUTION}.")
    w("Meshes are `FJxxxx.obj` files in millimetres; an `M` suffix mirrors the right side.")
    w("")
    w("## 1. What BodyParts3D contains")
    w("")
    w("| System | Meshes | Triangles (99 % set) |")
    w("|---|---:|---:|")
    for s, n in systems.most_common():
        w(f"| {SYSTEM_NAMES.get(s, s)} | {n} | {faces[s]:,} |")
    w(f"| **total** | **{len(rows)}** | **{sum(faces.values()):,}** |")
    w("")
    w("`catalog/bp3d-elements.json` lists every mesh with its FMA concept, side, volume and bounding box.")
    w("")

    w("## 2. Muscles used (right side; the left one mirrors it)")
    w("")
    w("| Muscle | Portuguese | Group | FMA concept (BodyParts3D) | Meshes | Base volume (cm³) |")
    w("|---|---|---|---|---|---:|")
    for mid, srcs, en, pt, group in anatomy.MUSCLES:
        concepts, files, vol = [], [], 0.0
        for s in srcs:
            for r in _rows_for(s, rows, by_name):
                concepts.append(f"{r['concept']} {r['name']}")
                files.append(r["file"])
                vol += r["volumeCm3"] or 0
        w(f"| {en} (`{mid}`) | {pt} | {group_label[group]} | {'; '.join(dict.fromkeys(concepts))} | "
          f"{', '.join(files)} | {vol:.0f} |")
    w("")

    w("## 3. Cut out and synthesized")
    w("")
    w("| Structure | How | Why |")
    w("|---|---|---|")
    w("| Rectus abdominis | cut out of mesh `FJ1452` (\"external oblique\") along the linea semilunaris measured "
      "on the surface (`split.py`) | in BodyParts3D 4.0 the external-oblique mesh is the whole anterior wall, "
      "tendinous intersections of the rectus included |")
    w("| Latissimus dorsi | fibres stretched over a distance field of the trunk, fleshy origin along the erectors "
      "and the iliac crest, insertion in the intertubercular sulcus (`synth.py`) | absent from BodyParts3D 4.0 |")
    w("| Patellar ligament | flat band from the apex of the patella to the tibial tuberosity (`synth.py`) | absent "
      "from BodyParts3D 4.0; without it the patella floats |")
    w("")

    w("## 4. Missing from BodyParts3D and not synthesized")
    w("")
    w("Internal oblique and transversus abdominis, quadratus lumborum, multifidus, muscles of mastication and "
      "facial expression, thoracolumbar fascia. They are deep (or covered) in a training context; they enter the "
      "muscle-mass budget through the coverage factor (`morph.COVERAGE`).")
    w("")

    w("## 5. BodyParts3D muscles left out")
    w("")
    used = set()
    for _mid, srcs, *_ in anatomy.MUSCLES:
        for s in srcs:
            if s.startswith("="):
                used.add(next(x for x in rows if x["file"] == s[1:])["name"])
            else:
                used.add(s)
                used.add(anatomy.left_name(s))
    left_out = sorted({r["name"] for r in rows if r["system"] == "muscle" and r["side"] != "left" and r["name"] not in used
                       and anatomy.left_name(r["name"]) not in used})
    w("Eye, ear, pharynx, larynx, tongue, heart, pelvic floor, diaphragm, internal and innermost intercostals, "
      "suboccipitals, rotatores/interspinales/intertransversarii, platysma and the posterior serrati — deep, "
      "visceral or covered by other muscles:")
    w("")
    w(", ".join(left_out) + ".")
    w("")

    w("## 6. Activatable groups")
    w("")
    w("| id | English | Portuguese | Area | Muscles |")
    w("|---|---|---|---|---|")
    members = collections.defaultdict(list)
    for _mid, _s, en, _pt, group in anatomy.MUSCLES:
        members[group].append(en)
    for _mid, en, _pt, group in anatomy.SYNTHETIC:
        members[group].append(en)
    for g, en, pt, area in anatomy.GROUPS:
        w(f"| `{g}` | {en} | {pt} | {area} | {', '.join(members[g])} |")
    w("")

    w("## 7. Training groups → model")
    w("")
    w("The gym vocabulary of `TRAINING_GROUPS`. Any of the id, the English or the Portuguese name activates the "
      "targets with the given weight (a fraction of the activation sent).")
    w("")
    w("| id | English | Portuguese | Targets (weight) |")
    w("|---|---|---|---|")
    for tid, en, pt, targets in anatomy.TRAINING_GROUPS:
        tg = ", ".join(f"{group_label.get(t, t)} ({v:g})" for t, v in targets.items())
        w(f"| `{tid}` | {en} | {pt} | {tg} |")
    w("")

    w("## 8. Fit regions")
    w("")
    w("One morph target per region (per side for the limbs); the weight of a region scales the hypertrophy of its "
      "groups (docs/body-fit.md).")
    w("")
    w("| id | English | Portuguese | Per side | Groups |")
    w("|---|---|---|---|---|")
    for rid, en, pt, sided, groups in anatomy.REGIONS:
        w(f"| `{rid}` | {en} | {pt} | {'yes' if sided else 'no'} | {', '.join(group_label[g] for g in groups)} |")
    w("")

    DOCS.mkdir(exist_ok=True)
    (DOCS / "catalog.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote docs/catalog.md ({len(out)} lines)")


if __name__ == "__main__":
    main()
